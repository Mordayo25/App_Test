/// Retorna la lista de categorías únicas presentes en la base de datos.
List<String> get categorias {
  final cats = signsDatabase.map((s) => s.categoria).toSet().toList();
  cats.sort();
  return ['Todas', ...cats];
}

/// Normaliza un texto eliminando tildes y signos comunes para búsquedas flexibles.
String _normalizarTexto(String input) {
  var text = input.toLowerCase();
  const Map<String, String> replacements = {
    'á': 'a',
    'é': 'e',
    'í': 'i',
    'ó': 'o',
    'ú': 'u',
    'ü': 'u',
    '¿': '',
    '¡': '',
    '?': '',
    '!': '',
  };
  replacements.forEach((key, value) {
    text = text.replaceAll(key, value);
  });
  return text.trim();
}

/// Filtra la base de datos por [query] (nombre) y/o [categoria].
/// La búsqueda ignora mayúsculas, minúsculas, tildes (á, é, í, ó, ú) y signos de puntuación.
List<SignModel> filtrarSenas({
  String query = '',
  String categoria = 'Todas',
}) {
  final queryNormalizado = _normalizarTexto(query);

  return signsDatabase.where((sign) {
    final palabraNormalizada = _normalizarTexto(sign.palabra);
    final matchQuery = queryNormalizado.isEmpty ||
        palabraNormalizada.contains(queryNormalizado);
    final matchCategoria =
        categoria == 'Todas' || sign.categoria == categoria;
    return matchQuery && matchCategoria;
  }).toList();
}

